/**
 * Build-time generator: flattens all site content and writes it to
 * netlify/functions/_site-knowledge.js for the serverless AI assistant.
 *
 * Emits:
 *   - SITE_ENTRIES : array of { title, page, path, text } — the assistant does
 *                    per-question retrieval over this so it only sends the
 *                    relevant slice of the site to the free LLM (saves tokens).
 *   - SYN          : the synonym map, so retrieval matches user vocabulary.
 *   - SITE_KNOWLEDGE : the full digest as one string (kept for reference).
 *
 * The assistant is told to answer ONLY from this content — keeping it grounded
 * in this website. Runs automatically before every build (see package.json).
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getKnowledgeText, getKnowledgeEntries, SYN } from '../src/data/knowledge.js'

const here = dirname(fileURLToPath(import.meta.url))
const entries = getKnowledgeEntries()
const text = getKnowledgeText()

// 1) For the Netlify function (Node).
const outDir = resolve(here, '../netlify/functions')
mkdirSync(outDir, { recursive: true })
writeFileSync(
  resolve(outDir, '_site-knowledge.js'),
  '// AUTO-GENERATED by scripts/gen-knowledge.mjs — do not edit by hand.\n' +
    'export const SITE_ENTRIES = ' + JSON.stringify(entries) + '\n' +
    'export const SYN = ' + JSON.stringify(SYN) + '\n' +
    'export const SITE_KNOWLEDGE = ' + JSON.stringify(text) + '\n',
  'utf8',
)

// 2) For the standalone Node AI server (your own / Jenkins host).
const serverDir = resolve(here, '../server')
mkdirSync(serverDir, { recursive: true })
writeFileSync(resolve(serverDir, 'site-knowledge.json'), JSON.stringify({ entries, syn: SYN }), 'utf8')

console.log(`gen-knowledge: wrote ${entries.length} entries (${text.length} chars) [Netlify + Node server]`)
